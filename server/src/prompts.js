export function system(modeKey) {
  const m = MODES[modeKey];
  return SYSTEM_TEMPLATE
    .replace("@@LABEL@@", m.label)
    .replace("@@TONE@@", m.tone)
    .replace("@@EXAMPLES@@", m.examples.split("\n").map((l) => "  " + l).join("\n"));
}

export function user(modeKey, spoken, screenText, myName = "", myRole = "", myStyle = []) {
  const m = MODES[modeKey];
  let s = "";
  if (myName.trim() || myRole.trim()) {
    s += "<보내는사람>" + [myName, myRole].filter((x) => x.trim()).join(", ") + "</보내는사람>\n\n";
  }
  if (screenText && screenText.trim()) {
    s += "<카톡화면에보이는글>\n" + screenText.slice(-SCREEN_CHARS) + "\n</카톡화면에보이는글>\n\n";
  }
  if (myStyle.length) {
    s += "<내평소말투>\n" + myStyle.map((x) => "- " + x).join("\n") + "\n</내평소말투>\n\n";
  }
  s += "<내가말한것>\n" + spoken.trim() + "\n</내가말한것>\n\n";
  s += "이 말을 '" + m.label + "' 말투의 카톡 메시지로 바꿔 주세요.";
  return s;
}

export function askUser(question, room, transcript) {
  let s = "";
  if (room && room.trim()) s += "대화방: " + room + "\n\n";
  s += "<대화기록>\n" + transcript.trim() + "\n</대화기록>\n\n";
  s += "<질문>" + question.trim() + "</질문>";
  return s;
}
